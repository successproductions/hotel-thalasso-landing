// Compiles the /dc-thermes styles (Tailwind v4) into src/dc-thermes/styles.generated.css.
// The rest of the site runs on Tailwind v3 through Next's PostCSS config, which cannot compile v4 syntax,
// so these pages get their own compiled file. Re-run after changing classes in src/dc-thermes:
//   npm run dc-thermes:css
import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';

const dir = path.resolve(import.meta.dirname, '../src/dc-thermes');
const from = path.join(dir, 'styles.css');
const to = path.join(dir, 'styles.generated.css');

// Tailwind v3 still runs over this file in Next's pipeline and rejects `@layer base|components|utilities`
// without its own directives, so the layers get a prefix (their order is unchanged).
const prefixLayers = {
  postcssPlugin: 'dc-thermes-prefix-layers',
  AtRule: {
    layer(rule) {
      if (rule.params.includes('dc-')) return;
      rule.params = rule.params
        .split(',')
        .map((name) => `dc-${name.trim()}`)
        .join(', ');
    },
  },
};

// `tailwindcss` at the project root is v3: use the v4 copy that ships with @tailwindcss/postcss
const require = createRequire(import.meta.url);
const v4Plugin = require.resolve('@tailwindcss/postcss');
const v4Css = createRequire(v4Plugin).resolve('tailwindcss/index.css');

const source = await fs.readFile(from, 'utf8');
const input = source.replace("@import 'tailwindcss'", `@import '${v4Css}'`);
const result = await postcss([
  tailwind({ base: dir, optimize: { minify: false } }),
  prefixLayers,
]).process(input, { from, to });

const banner = '/* Generated by scripts/build-dc-thermes-css.mjs from styles.css. Do not edit by hand. */\n';
await fs.writeFile(to, banner + result.css);
console.log(`${path.relative(process.cwd(), to)}: ${Math.round(result.css.length / 1024)} KB`);
